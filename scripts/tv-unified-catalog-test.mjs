import assert from 'node:assert/strict';
import fs from 'node:fs';
import {buildUnifiedCatalog,searchUnified,mixedUnified} from '../src/tvUnifiedCatalog.js';
import {PUBLISHER_FILMS} from '../src/officialCatalog.js';
import {PUBLISHER_SERIES} from '../src/publisherSeries.js';
import {PLAYLIST_SERIES} from '../src/publisherPlaylists.js';
import {ARABIC_SITE_SERIES} from '../src/arabicSiteCatalog.js';
import {DUBAI_PLUS_TITLES} from '../src/dubaiPlusCatalog.js';
const bulk=JSON.parse(fs.readFileSync('src/arabicBulkCatalog.json','utf8'));
const rows=buildUnifiedCatalog({films:PUBLISHER_FILMS,series:PUBLISHER_SERIES,playlists:PLAYLIST_SERIES,site:ARABIC_SITE_SERIES,bulk,dubai:DUBAI_PLUS_TITLES});
const variants=rows.flatMap(r=>r.variants);
assert.equal(variants.length,PUBLISHER_FILMS.length+PUBLISHER_SERIES.length+PLAYLIST_SERIES.length+ARABIC_SITE_SERIES.length+bulk.films.length+bulk.series.length+DUBAI_PLUS_TITLES.length);
assert.equal(variants.filter(x=>x.source==='dm-series').length,bulk.series.length);
assert.equal(variants.filter(x=>x.source==='dm-film').length,bulk.films.length);
assert(searchUnified(rows,'تتح').length>0);
assert(searchUnified(rows,'جعفر العمدة').length>0);
assert(mixedUnified(rows).length===rows.length);
const fixture=buildUnifiedCatalog({films:[{id:'one',title:'اختبار',year:'2020',kind:'فيلم'},{id:'two',title:'اختبار',year:'2021',kind:'فيلم'}],bulk:{series:[],films:[{id:'x123456',title:'اختبار',year:'2020'}]},auto:[{id:'a',title:'اختبار',year:'2020',kind:'movie'},{id:'b',title:'اختبار',kind:'movie'}]});
assert.equal(fixture.length,3);assert.equal(fixture.find(r=>r.year==='2020').variants.length,3);
assert.equal(searchUnified(fixture,'اختبار','tv').length,0);
assert.equal(searchUnified(fixture,'اختبار','movie').length,3);
console.log('Unified Arabic catalog:',rows.length,'groups;',variants.length,'source records; all static records retained, exact release grouping verified.');
