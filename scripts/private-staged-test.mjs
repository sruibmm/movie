import assert from 'node:assert/strict';
import {VERSION,structural,pickJobs,nextHealth,queueRows,effectiveDue,retryPlan,orderByCompletion} from '../worker/private-turbo-scheduler.js';
const now=Date.now();
const e=(id,n,phase)=>['episode:'+id+':'+n,{type:'episode',id,n,phase}];
const w=id=>['work:'+id,{type:'work',id}];
const index=['index:1',{type:'index'}];
const lanes=[[e('a',1),e('a',2),e('a',3),e('b',1),e('c',1),e('v',1,'verify')],[w('a'),w('b')],[index]];
assert.equal(VERSION,'auto-v9');
const fresh=pickJobs(lanes,20,new Map(),now);
assert.equal(fresh.filter(([,j])=>j.id==='a'&&j.type==='episode').length,1);
assert.equal(fresh.filter(([,j])=>j.type==='episode').length,4);
assert.equal(fresh[0][1].type,'index');
const known=pickJobs(lanes,20,new Map([['a',{success:true}]]),now);
assert.equal(known.filter(([,j])=>j.id==='a'&&j.type==='episode').length,3);
let h=nextHealth(undefined,false,'missing-direct-source',now);
assert.equal(h.failures,1);assert.equal(h.until,0);
h=nextHealth(h,false,'missing-direct-source',now);
assert.equal(h.until,now+15*60000);
const cooled=pickJobs(lanes,20,new Map([['a',h]]),now);
assert.equal(cooled.some(([,j])=>j.id==='a'&&j.type==='episode'),false);
assert.equal(cooled.some(([,j])=>j.id==='b'&&j.type==='episode'),true);
assert.equal(pickJobs(lanes,20,new Map([['a',h]]),h.until).some(([,j])=>j.id==='a'&&j.type==='episode'),true);
assert.equal(nextHealth(h,true,'',now).until,0);
assert.equal(nextHealth(h,true,'',now).success,true);
assert.equal(structural('missing-direct-source'),true);
assert.equal(structural('page-429'),false);
const rows=new Map(Array.from({length:1065},(_,i)=>['pc:q:'+String(i).padStart(4,'0'),{after:i<994?now+3600000:0}]));
const fakeStorage={async list({prefix,limit,startAfter}){return new Map([...rows].filter(([k])=>k.startsWith(prefix)&&(!startAfter||k>startAfter)).slice(0,limit));}};
const full=await queueRows(fakeStorage,'pc:q:',500);
assert.equal(full.size,1065);
assert.equal([...full.values()].filter(j=>effectiveDue(j,null,now)<=now).length,71);
assert.equal(effectiveDue({type:'episode',after:now+3600000},{until:now+60000},now,true),0);
assert.equal(effectiveDue({type:'episode',after:now+3600000},{until:now+60000},now,false),now+3600000);
assert.equal(effectiveDue({type:'episode',phase:'verify',after:0},{until:now+60000},now),0);
assert.equal(retryPlan('missing-direct-source',1,now).after,now+6*3600000);
assert.equal(retryPlan('page-429',1,now).after,now+30*60000);
assert.equal(retryPlan('page-503',1,now).after,now+60000);
const completion=orderByCompletion([e('far',1),e('near',1)],new Map([['far',{count:30,remaining:30}],['near',{count:30,remaining:2}]]),new Map(),now);
assert.equal(completion[0][1].id,'near');
console.log('STAGED TURBO PASS: fair sampling, cooldown, healthy work priority, extraction and verification scheduling');
