import fs from 'node:fs';
import assert from 'node:assert/strict';
import {normalizeArabic} from '../src/arabicDiscovery.js';
import {PUBLISHER_SERIES} from '../src/publisherSeries.js';
const read=p=>JSON.parse(fs.readFileSync(new URL('../'+p,import.meta.url),'utf8'));
const q=read('docs/arabic-bulk-queue.json');
const bulk=read('src/arabicBulkCatalog.json');
const a=read('docs/arabic-series-episode-audit-2026-11-15.json');
const b=read('docs/arabic-expansion-next-batch-2026-11-15.json');
const c=read('docs/arabic-library-consolidated-2026-11-15.json');
const d=read('docs/arabic-catalog-expansion-audit-2026-11-15.json');
const pending=new Map(q.pending.map(x=>[x.provider+':'+x.id,x]));
const known=new Set([...PUBLISHER_SERIES,...bulk.series].map(x=>normalizeArabic(x.title)));
const results=[],seen=new Set();
function group(provider,kind,title,id,episodes,extra={}){
 const refs=episodes.map(e=>provider+':'+e.id), fresh=refs.filter(r=>pending.has(r));
 if(!fresh.length)return;
 const key=provider+':'+kind+':'+id;
 if(seen.has(key))return;seen.add(key);
 const reasons=[];
 const nums=episodes.map(e=>e.number).sort((a,b)=>a-b);
 if(kind==='series'&&!nums.every((n,i)=>n===i+1))reasons.push('episode-number-gap-or-duplicate');
 if(kind==='series'&&known.has(normalizeArabic(title)))reasons.push('existing-title-review');
 if(kind==='series'&&!extra.canonicalComplete)reasons.push('canonical-season-length-unverified');
 if(!extra.hd)reasons.push('hd-unverified');
 if(!extra.adsFree)reasons.push('ad-free-unverified');
 if(!extra.identity)reasons.push('full-work-identity-unverified');
 reasons.push('live-playback-and-tv-unverified');
 results.push({key,provider,kind,title,referenceCount:refs.length,pendingCount:fresh.length,pendingIds:fresh,metadata:extra,reasons,status:'hold'});
}
for(const g of a.groups)group('youtube','series',g.title,g.id,g.episodes.map(([number,id])=>({number,id})),{publisher:g.author,source:g.authorUrl,metadataMatched:true});
for(const g of b.rows)group('dailymotion','series',g.title,g.playlist,g.episodes,{publisher:g.channel,hd:g.episodes.every(e=>e.hd===true),adsFree:g.episodes.every(e=>e.adsBlocked===true)});
for(const g of c.seriesCandidatesDetailed)group('dailymotion','series',g.title,g.id,g.episodes,{hd:g.episodes.every(e=>e.metadata?.hd===true),adsFree:g.episodes.every(e=>e.metadata?.adsBlocked===true)});
for(const f of c.filmCandidatesDetailed)group('dailymotion','film',f.title,f.id,[f],{publisher:f.owner,hd:f.metadata?.hd===true,adsFree:f.metadata?.adsBlocked===true});
for(const f of d.candidates)group('youtube','unclassified',f.title,f.video,[{id:f.video}],{publisher:f.publisherCheck?.author,metadataMatched:f.publisherCheck?.http===200,runtime:f.duration});
const covered=new Set(results.flatMap(x=>x.pendingIds));
assert.equal(covered.size,pending.size,'Missing pending references');
assert(results.every(x=>x.status==='hold'&&x.reasons.includes('live-playback-and-tv-unverified')));
const reasons={};for(const x of results)for(const r of x.reasons)reasons[r]=(reasons[r]||0)+1;
const report={schema:1,summary:{candidateGroups:results.length,pendingUniqueReferences:covered.size,approved:0,byKind:Object.fromEntries(['series','film','unclassified'].map(k=>[k,results.filter(x=>x.kind===k).length])),reasons},groups:results};
fs.writeFileSync(new URL('../docs/arabic-quality-gate.json',import.meta.url),JSON.stringify(report,null,2)+'\n');
console.log('QUALITY GATE',JSON.stringify(report.summary));
