import assert from 'node:assert/strict';
import {validDownloadPage,validDirectMedia,directFromDownloadHtml,refreshAkwam} from '../worker/akwam-link-refresh.js';

const download='https://akwam.ss/download/140992/76921/%D8%AC%D8%B9%D9%81%D8%B1-%D8%A7%D9%84%D8%B9%D9%85%D8%AF%D8%A9/%D8%A7%D9%84%D8%AD%D9%84%D9%82%D8%A9-30';
const link=n=>'https://s302d1.downet.net/download/'+n+'/test/Gaafar.Al.Omda.S01.E30.1080P.WEB-DL.AKWAM.mp4';
assert.equal(validDownloadPage(download),true);
assert.equal(validDownloadPage('http://akwam.ss/download/140992/76921/a'),false);
assert.equal(validDownloadPage('https://akwam.ss.evil.test/download/140992/76921/a'),false);
assert.equal(validDirectMedia(link(101)),true);
assert.equal(validDirectMedia('https://s302d1.downet.net.evil.test/download/a.mp4'),false);
assert.equal(validDirectMedia('https://127.0.0.1/download/a.mp4'),false);
assert.equal(validDirectMedia('https://s302d1.downet.net/download/a.m3u8'),false);
const html=n=>'<main><a href="'+link(n)+'">Download MP4</a></main>';
assert.equal(directFromDownloadHtml(html(101),download),link(101));
assert.equal(directFromDownloadHtml('<a href="'+link(101).replace(/&/g,'&amp;')+'">Video</a>',download),link(101));
assert.throws(()=>directFromDownloadHtml('<a href="https://evil.test/file.mp4">bad</a>',download),/no-approved/);
assert.throws(()=>directFromDownloadHtml(html(101)+html(102),download),/ambiguous/);

const now=1794900000000;
const rights={reference:'OPERATOR-TEST-ONLY',webPlayback:true,territories:['KW'],expires:'2099-01-01'};
const makeEnv=(r=rights)=>({CINEMA_TERRITORY:'KW',AKWAM_APPROVED_ASSETS_JSON:JSON.stringify({version:1,assets:[{id:'jaafar-e30-1080',quality:'1080p',downloadPage:download,rights:r}]})});
const req=()=>new Request('https://cinema.test/api/private-catalog/akwam-refresh?id=jaafar-e30-1080');
let calls=0;
const fetcher=async(url,options)=>{calls++;assert.equal(url,download);assert.equal(options.redirect,'manual');return new Response(html(100+calls),{status:200,headers:{'Content-Type':'text/html; charset=utf-8'}});};
let r=await refreshAkwam(req(),makeEnv(),fetcher,now);
assert.equal(r.status,200);
assert.equal((await r.json()).url,link(101));
r=await refreshAkwam(req(),makeEnv(),fetcher,now+1000);
assert.equal((await r.json()).url,link(101));
assert.equal(calls,1,'cache avoids duplicate source requests');
r=await refreshAkwam(req(),makeEnv(),fetcher,now+21_000);
assert.equal((await r.json()).url,link(102),'link refreshes after short TTL');
assert.equal(calls,2);
r=await refreshAkwam(req(),makeEnv({...rights,expires:'2000-01-01'}),fetcher,now+22_000);
assert.equal(r.status,403,'expired rights gate');
assert.equal(calls,2);
r=await refreshAkwam(req(),{},fetcher,now+23_000);
assert.equal(r.status,403,'no manifest');
assert.equal(calls,2);
r=await refreshAkwam(new Request('https://cinema.test/api/private-catalog/akwam-refresh?id=../x'),makeEnv(),fetcher,now+24_000);
assert.equal(r.status,400,'no arbitrary page URL');
assert.equal(calls,2);
r=await refreshAkwam(new Request('https://cinema.test/api/private-catalog/akwam-refresh?id=not-listed'),makeEnv(),fetcher,now+25_000);
assert.equal(r.status,404,'unknown asset');
r=await refreshAkwam(req(),makeEnv(),async()=>new Response('',{status:429}),now+45_000);
assert.equal(r.status,502);
assert.equal((await r.json()).error,'source-rate-limited');
console.log('AKWAM PRIVATE REFRESH PASS: exact hosts, parse, refresh, TTL, rights, IDs, rate limits');
